def _rel_project_path(value: Any) -> str:
    """Return a project-relative path string for repo portability."""
    if value is None:
        return ""
    raw = str(value).strip()
    if not raw:
        return ""
    raw = raw.replace("\\", "/")
    try:
        p = Path(raw)
        if p.is_absolute():
            return str(p.resolve().relative_to(ROOT)).replace("\\", "/")
    except Exception:
        pass
    m = re.search(r"(?:^|.*?)(data[\/].*)$", raw)
    if m:
        return m.group(1).replace("\\", "/")
    m = re.search(r"(?:^|.*?)(workspace[\/].*)$", raw)
    if m:
        return m.group(1).replace("\\", "/")
    m = re.search(r"(?:^|.*?)(src[\/].*)$", raw)
    if m:
        return m.group(1).replace("\\", "/")
    return raw.replace("\\", "/")


def _relativize_dict_paths(data: Any) -> Any:
    if isinstance(data, dict):
        return {k: _relativize_dict_paths(v) for k, v in data.items()}
    if isinstance(data, list):
        return [_relativize_dict_paths(v) for v in data]
    if isinstance(data, (str, Path)):
        s = str(data)
        if "data" in s or "workspace" in s or ":\\" in s or ":/" in s or s.startswith("/"):
            return _rel_project_path(s)
    return data



def _load_kipris_tech_ml_features(cdir: str, tech_output_dir: Path) -> dict[str, Any]:
    """Load KIPRIS Tech ML feature JSON generated by build_kipris_tech_ml_features.py.

    This does not fetch KIPRIS again.
    It only connects the already-created feature JSON into Tech Agent runtime outputs.
    """
    candidates = [
        tech_output_dir / f"{cdir}_kipris_tech_ml_features.json",
        tech_output_dir / "kipris_tech_ml_features.json",
    ]
    candidates.extend(sorted(tech_output_dir.glob("*kipris*tech_ml*features*.json")))

    for candidate in candidates:
        try:
            if candidate.exists() and candidate.is_file():
                payload = json.loads(candidate.read_text(encoding="utf-8"))
                if isinstance(payload, dict):
                    payload.setdefault("_source_file", _rel_project_path(candidate))
                    return payload
        except Exception as exc:
            print(f"[Tech Agent] KIPRIS Tech ML feature load skipped: {candidate} / {exc}")

    return {}


def _merge_kipris_tech_ml_into_bridge(
    bridge: dict[str, Any],
    kipris_features: dict[str, Any],
) -> dict[str, Any]:
    """Apply conservative KIPRIS/IP feature adjustment to Tech-to-Value Bridge."""
    if not isinstance(bridge, dict):
        bridge = {}

    if not kipris_features:
        return bridge

    scores = kipris_features.get("scores") or {}
    adjustment = kipris_features.get("tech_to_value_bridge_adjustment") or {}

    try:
        adj_points = float(adjustment.get("bridge_adjustment_points") or 0)
    except Exception:
        adj_points = 0.0

    base_score = bridge.get("score")
    try:
        base_score_f = float(base_score)
    except Exception:
        base_score_f = None

    if base_score_f is not None and adj_points:
        bridge["score_before_kipris_tech_ml_adjustment"] = base_score_f
        bridge["score"] = round(max(0.0, min(100.0, base_score_f + adj_points)), 2)

    bridge["kipris_tech_ml_features"] = kipris_features
    bridge["kipris_tech_ml_score"] = scores.get("kipris_tech_ml_score")
    bridge["legal_stability_score_estimated"] = scores.get("legal_stability_score_estimated")
    bridge["portfolio_momentum_score"] = scores.get("portfolio_momentum_score")
    bridge["ip_technology_fit_score"] = scores.get("ip_technology_fit_score")
    bridge["bridge_adjustment_points"] = adjustment.get("bridge_adjustment_points")
    bridge["bridge_signal"] = adjustment.get("bridge_signal")
    bridge["kipris_bridge_usage_rule"] = adjustment.get("usage_rule")
    bridge["kipris_bridge_applied"] = True

    return bridge


