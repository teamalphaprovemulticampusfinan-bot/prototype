def resolve_company_dir(company:str)->str:
    raw=str(company or "").strip().strip('"').strip("'")
    if not raw:
        raise ValueError("회사 입력값이 비어 있습니다.")
    p=Path(raw)
    if not p.is_absolute():
        p=ROOT/p
    if p.name.lower()=="company.yaml":
        return company_slug(p.parent.parent.name if p.parent.name == "common" else p.parent.name)
    if p.exists() and p.is_dir() and (p/"common"/"company.yaml").exists():
        return company_slug(p.name)
    return company_slug(raw)

def load_company(company_dir:str)->dict[str,Any]:
    p=company_config_path(company_dir)
    if not p.exists():
        raise FileNotFoundError(f"회사 설정 파일이 없습니다: {p}")
    d=yaml.safe_load(p.read_text(encoding="utf-8")) or {}
    d.setdefault("slug", company_slug(company_dir))
    return d

