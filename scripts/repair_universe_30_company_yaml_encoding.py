from __future__ import annotations

import argparse
import csv
import json
import shutil
from datetime import datetime
from pathlib import Path


DEFAULT_CSV = Path("data/반도체/_sector_common/universe/universe_30_semiconductor_20260514.csv")
DEFAULT_FIELD = "반도체"


def read_csv_utf8(csv_path: Path) -> list[dict[str, str]]:
    if not csv_path.exists():
        raise FileNotFoundError(f"Universe CSV not found: {csv_path}")

    encodings = ["utf-8-sig", "utf-8", "cp949"]
    last_error: Exception | None = None

    for enc in encodings:
        try:
            with csv_path.open("r", encoding=enc, newline="") as f:
                rows = list(csv.DictReader(f))
            if rows:
                return rows
        except Exception as exc:
            last_error = exc

    raise RuntimeError(f"Could not read CSV with encodings {encodings}: {last_error}")


def q(value: object) -> str:
    text = "" if value is None else str(value)
    text = text.replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def truthy(value: object) -> bool:
    return str(value).strip().lower() in {"1", "true", "yes", "y"}


def yahoo_ticker(stock_code: str, market: str) -> str:
    code = str(stock_code).strip().zfill(6)
    m = str(market).strip().upper()

    if m == "KOSPI":
        return f"{code}.KS"
    if m == "KOSDAQ":
        return f"{code}.KQ"
    return code


def render_company_yaml(row: dict[str, str], universe_name: str, locked_as_of: str) -> str:
    company_name = row.get("company_name", "").strip()
    company_dir = row.get("company_dir", "").strip()
    stock_code = row.get("stock_code", "").strip().zfill(6)
    market = row.get("market", "").strip()
    field = (row.get("field") or row.get("sector") or DEFAULT_FIELD).strip()
    sector = (row.get("sector") or field).strip()
    peer_group = row.get("peer_group", "").strip()
    ticker = yahoo_ticker(stock_code, market)

    finance_file = f"{company_name}_재무.csv"
    stock_file = f"{company_name}_주식.csv"

    lines = [
        "# Auto-generated by scripts/repair_universe_30_company_yaml_encoding.py",
        "# Korean text is written as UTF-8. Do not edit after evaluation start unless the universe lock is intentionally revised.",
        f"slug: {q(company_dir)}",
        f"company_dir: {q(company_dir)}",
        f"corp_name: {q(company_name)}",
        f"display_name: {q(company_name)}",
        f"output_name: {q(company_name)}",
        f"field: {q(field)}",
        f"industry_field: {q(field)}",
        f"sector: {q(sector)}",
        f"peer_group: {q(peer_group)}",
        f"stock_code: {q(stock_code)}",
        f"ticker: {q(ticker)}",
        f"market: {q(market)}",
        "include_in_evaluation: true",
        f"universe_name: {q(universe_name)}",
        f"universe_source: {q('Tech/Valuation peer universe filtered to semiconductor 30')}",
        f"selection_bucket: {q(peer_group)}",
        f"selection_reason: {q('B-plan semiconductor value-chain universe; fixed before evaluation.')}",
        f"locked_as_of: {q(locked_as_of)}",
        f"finance_file: {q(finance_file)}",
        f"stock_file: {q(stock_file)}",
        "aliases:",
        f"  - {q(company_name)}",
        f"  - {q(company_dir)}",
        f"  - {q(stock_code)}",
        f"  - {q(ticker)}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(
        description="Repair mojibake company.yaml files for the AlphaProve semiconductor universe."
    )
    parser.add_argument("--csv", default=str(DEFAULT_CSV), help="Universe CSV path")
    parser.add_argument("--field", default=DEFAULT_FIELD, help="Data field folder name, usually 반도체")
    parser.add_argument("--universe-name", default="universe_30_semiconductor_20260514")
    parser.add_argument("--locked-as-of", default="2026-05-14")
    parser.add_argument("--no-backup", action="store_true", help="Do not create .encoding_bak backup files")
    parser.add_argument("--dry-run", action="store_true")
    args = parser.parse_args()

    csv_path = Path(args.csv)
    rows = read_csv_utf8(csv_path)

    root = Path("data") / args.field
    report: list[dict[str, str]] = []

    for row in rows:
        if not truthy(row.get("include_in_evaluation", "1")):
            continue

        company_name = row.get("company_name", "").strip()
        company_dir = row.get("company_dir", "").strip()

        if not company_name or not company_dir:
            raise ValueError(f"Missing company_name/company_dir in row: {row}")

        company_root = root / company_name
        yaml_dir = company_root / "_company_common"
        yaml_path = yaml_dir / "company.yaml"

        clean_yaml = render_company_yaml(
            row=row,
            universe_name=args.universe_name,
            locked_as_of=args.locked_as_of,
        )

        action = "would_write" if args.dry_run else "written"

        if not args.dry_run:
            yaml_dir.mkdir(parents=True, exist_ok=True)

            if yaml_path.exists() and not args.no_backup:
                backup_path = yaml_path.with_suffix(".yaml.encoding_bak")
                if not backup_path.exists():
                    shutil.copy2(yaml_path, backup_path)

            yaml_path.write_text(clean_yaml, encoding="utf-8")

        report.append(
            {
                "company_name": company_name,
                "company_dir": company_dir,
                "yaml_path": str(yaml_path),
                "action": action,
            }
        )

    report_path = root / "_sector_common" / "universe" / "universe_30_company_yaml_encoding_repair_report.json"

    if not args.dry_run:
        report_path.parent.mkdir(parents=True, exist_ok=True)
        report_path.write_text(
            json.dumps(
                {
                    "status": "OK",
                    "created_at": datetime.now().isoformat(timespec="seconds"),
                    "csv": str(csv_path),
                    "count": len(report),
                    "items": report,
                },
                ensure_ascii=False,
                indent=2,
            ),
            encoding="utf-8",
        )

    print(f"[OK] target_count={len(report)} dry_run={args.dry_run}")
    for item in report[:5]:
        print(f" - {item['company_name']} -> {item['yaml_path']} ({item['action']})")
    if len(report) > 5:
        print(f" ... and {len(report) - 5} more")
    if not args.dry_run:
        print(f"[REPORT] {report_path}")

    return 0


if __name__ == "__main__":
    raise SystemExit(main())
